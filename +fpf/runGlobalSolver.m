function [solution,objectiveValue,exitFlag,output,solverName] = ...
    runGlobalSolver(objective,lowerBounds,upperBounds,initialPoint,...
    solverIndex,stageName,options)
%RUNGLOBALSOLVER Run one supported scalar global optimization algorithm.

    arguments
        objective (1,1) function_handle
        lowerBounds (1,:) double
        upperBounds (1,:) double
        initialPoint (1,:) double
        solverIndex (1,1) double {mustBeInteger,mustBeGreaterThanOrEqual(solverIndex,0),mustBeLessThanOrEqual(solverIndex,5)}
        stageName (1,1) string {mustBeMember(stageName,["reference","mzi"])}
        options.Display (1,1) string {mustBeMember(options.Display,["off","final","iter","diagnose"])} = "iter"
    end

    reporter = fpf.currentReporter();
    if ~isempty(reporter)
        reporter.stage(stageName);
        originalObjective = objective;
        objective = @reportedObjective;
    end
    numberOfVariables = numel(initialPoint);
    if numel(lowerBounds) ~= numberOfVariables || ...
            numel(upperBounds) ~= numberOfVariables
        error("fpf:InvalidBounds","Bounds and initial point must have equal lengths.");
    end

    switch solverIndex
        case 0
            solverName = "ga";
            maxGenerations = 200;
            if stageName == "reference"
                maxGenerations = 2000;
            end
            populationSize = max(80,20.*numberOfVariables);
            initialPopulation = fpf.generateInitialPoints(...
                lowerBounds,upperBounds,populationSize,stageName);
            initialPopulation(1,:) = initialPoint;
            options = optimoptions("ga",...
                "Display",options.Display,...
                "FunctionTolerance",1e-10,...
                "MaxGenerations",maxGenerations,...
                "MaxStallGenerations",60,...
                "PopulationSize",populationSize,...
                "InitialPopulationMatrix",initialPopulation,...
                "UseParallel",false,...
                "UseVectorized",false);
            [solution,objectiveValue,exitFlag,output] = ga(objective,...
                numberOfVariables,[],[],[],[],lowerBounds,upperBounds,[],options);
        case 1
            solverName = "particleswarm";
            swarmSize = max(100,20.*numberOfVariables);
            initialSwarm = fpf.generateInitialPoints(...
                lowerBounds,upperBounds,swarmSize,stageName);
            initialSwarm(1,:) = initialPoint;
            options = optimoptions("particleswarm",...
                "Display",options.Display,...
                "FunctionTolerance",1e-10,...
                "InitialSwarmMatrix",initialSwarm,...
                "MaxIterations",2000,...
                "MaxStallIterations",60,...
                "SwarmSize",swarmSize,...
                "UseParallel",false,...
                "UseVectorized",false);
            [solution,objectiveValue,exitFlag,output] = particleswarm(objective,...
                numberOfVariables,lowerBounds,upperBounds,options);
        case 2
            solverName = "surrogateopt";
            functionTolerance = 1e-10;
            maxStallEvaluations = 200;
            stallOutputFunction = @(point,values,state) ...
                fpf.stopWhenObjectiveStalls(point,values,state,...
                functionTolerance,maxStallEvaluations);
            initialPointCount = max(20,2.*numberOfVariables);
            initialPoints = fpf.generateInitialPoints(...
                lowerBounds,upperBounds,initialPointCount,stageName);
            initialPoints(1,:) = initialPoint;
            options = optimoptions("surrogateopt",...
                "Display",options.Display,...
                "InitialPoints",initialPoints,...
                "MaxFunctionEvaluations",4000,...
                "MaxTime",400,...
                "ObjectiveLimit",functionTolerance,...
                "OutputFcn",stallOutputFunction,...
                "PlotFcn",[],...
                "UseParallel",false);
            [solution,objectiveValue,exitFlag,output] = surrogateopt(...
                objective,lowerBounds,upperBounds,options);
        case 3
            solverName = "simulannealbnd";
            options = optimoptions("simulannealbnd",...
                "Display",options.Display,...
                "FunctionTolerance",1e-10,...
                "MaxIterations",2000,...
                "MaxStallIterations",60,...
                "MaxFunctionEvaluations",20000,...
                "ReannealInterval",100);
            [solution,objectiveValue,exitFlag,output] = simulannealbnd(...
                objective,initialPoint,lowerBounds,upperBounds,options);
        case 4
            solverName = "patternsearch";
            options = optimoptions("patternsearch",...
                "Display",options.Display,...
                "FunctionTolerance",1e-10,...
                "MaxIterations",200,...
                "UseCompletePoll",false,...
                "UseCompleteSearch",false,...
                "UseParallel",false);
            [solution,objectiveValue,exitFlag,output] = patternsearch(...
                objective,initialPoint,[],[],[],[],lowerBounds,upperBounds,[],options);
        case 5
            solverName = "paretosearch";
            populationSize = max(100,20.*numberOfVariables);
            initialPoints = fpf.generateInitialPoints(...
                lowerBounds,upperBounds,populationSize,stageName);
            initialPoints(1,:) = initialPoint;
            options = optimoptions("paretosearch",...
                "ConstraintTolerance",1e-10,...
                "Display",options.Display,...
                "InitialPoints",initialPoints,...
                "MaxFunctionEvaluations",20000,...
                "MaxIterations",400,...
                "MaxTime",400,...
                "MeshTolerance",1e-6,...
                "MinPollFraction",0,...
                "UseParallel",false,...
                "UseVectorized",false);
            [solutions,objectiveValues,exitFlag,output] = paretosearch(...
                objective,numberOfVariables,[],[],[],[],...
                lowerBounds,upperBounds,[],options);
            [objectiveValue,bestIndex] = min(objectiveValues);
            solution = solutions(bestIndex,:);
        otherwise
            error("fpf:UnsupportedSolver","Unsupported solver index %d.",solverIndex);
    end
    function value = reportedObjective(candidate)
        value = originalObjective(candidate);
        reporter.evaluated(value);
    end
end
