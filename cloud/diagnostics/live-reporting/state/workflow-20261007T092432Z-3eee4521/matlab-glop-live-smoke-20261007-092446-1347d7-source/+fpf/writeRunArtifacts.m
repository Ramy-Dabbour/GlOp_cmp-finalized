function artifacts = writeRunArtifacts(runResult)
%WRITERUNARTIFACTS Save figures and detailed data for one completed run.

    arguments
        runResult (1,1) struct
    end

    packageDirectory = fileparts(mfilename("fullpath"));
    [figureHandle,plotData] = fpf.plotResponses(...
        runResult.mziResult,runResult.N_s);
    figureStem = fullfile(packageDirectory,...
        "FIR_filter_response_comparison");
    figureFilePaths = struct(...
        "fig",figureStem + ".fig",...
        "pdf",figureStem + ".pdf",...
        "png",figureStem + ".png");
    savefig(figureHandle,figureFilePaths.fig);
    print(figureHandle,figureFilePaths.pdf,"-dpdf","-bestfit");
    print(figureHandle,figureFilePaths.png,"-dpng","-r300");

    firOrder = runResult.firOrder;
    tapCount = runResult.tapCount;
    N_s = runResult.N_s;
    passbandRatio = runResult.passbandRatio;
    randomSeed = runResult.randomSeed;
    referenceSolver = runResult.referenceSolver;
    mziSolver = runResult.mziSolver;
    rawSincReference = runResult.rawSincReference;
    x = runResult.x;
    referenceResult = runResult.referenceResult;
    mziResult = runResult.mziResult;
    efficiencyMetrics = struct(...
        "reference",referenceResult.metrics,...
        "mzi",mziResult.metrics);
    optimizedPhysicalParameters = struct(...
        "theta",mziResult.theta,...
        "phiFixed",mziResult.phiFixed,...
        "phaseShiftPattern",mziResult.phaseShiftPattern,...
        "design",mziResult.design);
    outputDataPath = fullfile(packageDirectory,"output_data.mat");
    save(outputDataPath,...
        "firOrder","tapCount","N_s","passbandRatio","randomSeed",...
        "referenceSolver","mziSolver",...
        "rawSincReference","x","referenceResult",...
        "optimizedPhysicalParameters","mziResult","efficiencyMetrics",...
        "figureHandle","plotData","figureFilePaths",...
        "-mat","-nocompression");

    artifacts = struct(...
        "figureHandle",figureHandle,...
        "figureFilePaths",figureFilePaths,...
        "outputData",outputDataPath);
end
