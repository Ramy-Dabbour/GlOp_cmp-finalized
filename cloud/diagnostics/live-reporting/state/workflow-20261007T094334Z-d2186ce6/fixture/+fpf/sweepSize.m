function workSize = sweepSize(config)
%SWEEPSIZE Validate a sweep and return its fastest-to-slowest index dimensions.
    validateattributes(config,"struct",{"scalar"});
    validateattributes(config.firOrders,"double",...
        {"vector","nonempty","real","finite","integer",">=",1,"<=",254});
    validateattributes(config.passbandRatios,"double",...
        {"vector","nonempty","real","finite",">",0,"<",1});
    validateattributes(config.randomSeeds,"double",...
        {"vector","nonempty","real","finite","integer",">=",0,"<=",4294967295});
    validateattributes(config.N_tr,"double",...
        {"scalar","real","finite","integer",">=",1});
    validateattributes(config.N_s,"double",...
        {"scalar","real","finite","integer",">=",2});
    validateattributes(config.referenceSolvers,"double",...
        {"vector","nonempty","real","finite","integer",">=",0,"<=",5});
    validateattributes(config.mziSolvers,"double",...
        {"vector","nonempty","real","finite","integer",">=",0,"<=",5});
    if numel(unique(config.referenceSolvers)) ~= numel(config.referenceSolvers) || ...
            numel(unique(config.mziSolvers)) ~= numel(config.mziSolvers)
        error("fpf:DuplicateSolver","Solver lists must contain unique indices.");
    end
    workSize = [config.N_tr,numel(config.mziSolvers),...
        numel(config.referenceSolvers),numel(config.firOrders),...
        numel(config.passbandRatios),numel(config.randomSeeds)];
    if prod(workSize) > flintmax
        error("fpf:SweepTooLarge","The trial count must be exactly representable.");
    end
end
