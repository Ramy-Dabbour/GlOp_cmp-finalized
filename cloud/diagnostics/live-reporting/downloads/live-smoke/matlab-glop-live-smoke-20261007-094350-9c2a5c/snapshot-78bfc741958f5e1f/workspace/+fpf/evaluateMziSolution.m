function result = evaluateMziSolution(...
        design,stageCount,referenceCoefficientMatrix,options)
%EVALUATEMZISOLUTION Calculate MZI responses and their reference error.

    arguments
        design
        stageCount
        referenceCoefficientMatrix
        options.CollectDiagnostics (1,1) logical = true
    end

    [theta,phiFixed,phaseShiftPattern] = fpf.unpackMziDesign(...
        design,stageCount);
    zCoefficientMatrix = fpf.mziSMatrixCoefficients(...
        theta,phaseShiftPattern);
    [realizedCoefficientMatrix,isResponseNormalized] = ...
        fpf.realizedSMatrixLagCoefficients(zCoefficientMatrix);
    coefficientDifference = ...
        realizedCoefficientMatrix - referenceCoefficientMatrix;
    referenceNorm = norm(referenceCoefficientMatrix,"fro");

    if isResponseNormalized && referenceNorm > 0
        normalizedFrobeniusError = ...
            norm(coefficientDifference,"fro")./referenceNorm;
    else
        normalizedFrobeniusError = realmax;
    end

    result = struct( ...
        "design",design(:).', ...
        "theta",theta, ...
        "phiFixed",phiFixed, ...
        "phaseShiftPattern",phaseShiftPattern, ...
        "zCoefficientMatrix",zCoefficientMatrix, ...
        "referenceCoefficientMatrix",referenceCoefficientMatrix, ...
        "realizedCoefficientMatrix",realizedCoefficientMatrix, ...
        "coefficientDifference",[], ...
        "isResponseNormalized",isResponseNormalized, ...
        "normalizedFrobeniusError",normalizedFrobeniusError, ...
        "rmsCoefficientError",NaN);
    if options.CollectDiagnostics
        result.coefficientDifference = coefficientDifference;
        result.rmsCoefficientError = ...
            sqrt(mean(abs(coefficientDifference(:)).^2));
    end
end
