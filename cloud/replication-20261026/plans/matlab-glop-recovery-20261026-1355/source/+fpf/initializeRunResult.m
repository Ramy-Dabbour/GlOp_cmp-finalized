function result = initializeRunResult(firOrder,passbandRatio,...
        referenceSolver,mziSolver,N_s,randomSeed,trialIndex)
%INITIALIZERUNRESULT Allocate one sequential solver-pair trial result.

    result = struct(...
        "firOrder",firOrder,...
        "tapCount",firOrder + 1,...
        "passbandRatio",passbandRatio,...
        "referenceSolver",referenceSolver,...
        "mziSolver",mziSolver,...
        "N_s",N_s,...
        "randomSeed",randomSeed,...
        "trialIndex",trialIndex,...
        "completed",false,...
        "success",false,...
        "failureStage","",...
        "failureIdentifier","",...
        "failureMessage","",...
        "rawSincReference",[],...
        "x",[],...
        "referenceResult",[],...
        "mziResult",[],...
        "accuracy",struct("reference",NaN,...
            "normalizedFrobenius",NaN,"rmsCoefficient",NaN),...
        "artifacts",struct());
end
