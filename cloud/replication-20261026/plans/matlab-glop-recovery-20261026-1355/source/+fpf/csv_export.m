function csvPath = csv_export(matFilePath,csvFilePath)
%CSV_EXPORT Export saved aggregate solver-pair favorability to a CSV file.
%   CSVPATH = FPF.CSV_EXPORT(MATFILEPATH) reads benchmarkResults from MATFILEPATH
%   and writes a CSV with the same directory and basename. With no arguments,
%   the source is benchmark_results.mat in the project directory.
%   CSVPATH = FPF.CSV_EXPORT(MATFILEPATH,CSVFILEPATH) selects the destination.

arguments
    matFilePath {mustBeTextScalar,mustBeNonzeroLengthText} = ...
        fullfile(fileparts(fileparts(mfilename('fullpath'))),'benchmark_results.mat')
    csvFilePath {mustBeTextScalar,mustBeNonzeroLengthText} = fpf.defaultCsvPath(matFilePath)
end

savedResults = load(matFilePath,'benchmarkResults');
if ~isfield(savedResults,'benchmarkResults')
    error('fpf:csv_export:MissingResults', ...
        'The MAT file must contain benchmarkResults.');
end
benchmarkResults = savedResults.benchmarkResults;
expectedNames = {'referenceSolver','mziSolver','favorabilityIndex'};
if ~istable(benchmarkResults) || ...
        ~isequal(benchmarkResults.Properties.VariableNames,expectedNames)
    error('fpf:csv_export:InvalidResults', ...
        'benchmarkResults must be a table with referenceSolver, mziSolver, and favorabilityIndex columns.');
end
if ~isstring(benchmarkResults.referenceSolver) || ...
        size(benchmarkResults.referenceSolver,2) ~= 1 || ...
        ~isstring(benchmarkResults.mziSolver) || ...
        size(benchmarkResults.mziSolver,2) ~= 1 || ...
        ~isa(benchmarkResults.favorabilityIndex,'double') || ...
        ~isreal(benchmarkResults.favorabilityIndex) || ...
        size(benchmarkResults.favorabilityIndex,2) ~= 1
    error('fpf:csv_export:InvalidColumns', ...
        'Solver columns must be string columns and favorabilityIndex must be a real double column.');
end
if height(unique(benchmarkResults(:,1:2),'rows')) ~= height(benchmarkResults)
    error('fpf:csv_export:DuplicateSolverPair', ...
        'benchmarkResults must contain at most one row per solver pair.');
end

csvPath = string(csvFilePath);
writetable(benchmarkResults,csvPath);
end

% Legacy stage-level exporters are retained but disabled. The active exporter
% above writes only the aggregate favorability table saved in the MAT file.
%{
load('benchmark_results.mat','benchmarkResults');
br = benchmarkResults;
firOrders = br.inputs.firOrders;
passbandRatios = br.inputs.passbandRatios;
randomSeeds = br.inputs.randomSeeds;
solverNames = br.solvers.names;

col = @(x) reshape(x,[],1);   % forces any array to a column, unconditionally

% ----- Reference stage -----
[fg,pg,sg,rg] = ndgrid(1:numel(firOrders),1:numel(passbandRatios),...
    1:numel(randomSeeds),1:numel(solverNames));
refTable = table(col(firOrders(fg(:))),col(passbandRatios(pg(:))),col(randomSeeds(sg(:))),...
    col(solverNames(rg(:))),...
    col(br.referenceStage.normalizedCoefficientError),col(br.referenceStage.elapsedSeconds),...
    col(br.referenceStage.functionEvaluations),col(br.referenceStage.progressCount),...
    col(string(br.referenceStage.progressUnit)),col(br.referenceStage.exitFlag),...
    col(br.referenceStage.completed),col(br.referenceStage.converged),...
    col(br.referenceStage.validSolution),col(string(br.referenceStage.failureIdentifier)),...
    col(string(br.referenceStage.failureMessage)),...
    'VariableNames',{'firOrder','passbandRatio','randomSeed','referenceSolver',...
    'normalizedCoefficientError','elapsedSeconds','functionEvaluations','progressCount',...
    'progressUnit','exitFlag','completed','converged','validSolution',...
    'failureIdentifier','failureMessage'});
writetable(refTable,'reference_stage.csv');

% ----- MZI stage -----
[fg,pg,sg,rg,mg] = ndgrid(1:numel(firOrders),1:numel(passbandRatios),...
    1:numel(randomSeeds),1:numel(solverNames),1:numel(solverNames));
mziTable = table(col(firOrders(fg(:))),col(passbandRatios(pg(:))),col(randomSeeds(sg(:))),...
    col(solverNames(rg(:))),col(solverNames(mg(:))),...
    col(br.mziStage.normalizedFrobeniusError),col(br.mziStage.rmsCoefficientError),...
    col(br.mziStage.objectiveValue),col(br.mziStage.elapsedSeconds),...
    col(br.mziStage.functionEvaluations),col(br.mziStage.progressCount),...
    col(string(br.mziStage.progressUnit)),col(br.mziStage.exitFlag),...
    col(br.mziStage.completed),col(br.mziStage.converged),col(br.mziStage.validSolution),...
    col(string(br.mziStage.failureIdentifier)),col(string(br.mziStage.failureMessage)),...
    'VariableNames',{'firOrder','passbandRatio','randomSeed','referenceSolver','mziSolver',...
    'normalizedFrobeniusError','rmsCoefficientError','objectiveValue','elapsedSeconds',...
    'functionEvaluations','progressCount','progressUnit','exitFlag','completed','converged',...
    'validSolution','failureIdentifier','failureMessage'});
writetable(mziTable,'mzi_stage.csv');
%}
