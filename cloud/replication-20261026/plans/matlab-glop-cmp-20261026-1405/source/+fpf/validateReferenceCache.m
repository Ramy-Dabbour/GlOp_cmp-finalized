function validateReferenceCache(cache,firOrder,passbandRatio,...
        referenceSolver,randomSeed)
%VALIDATEREFERENCECACHE Legacy cache validator, retained but no longer used.
%   Every trial now runs a fresh reference optimization in fpf.run.

    requiredFields = ["firOrder","passbandRatio","referenceSolver",...
        "randomSeed","rawSincReference","referenceResult","mziRandomState"];
    isValid = isstruct(cache) && isscalar(cache) && ...
        all(isfield(cache,requiredFields)) && ...
        isequal(cache.firOrder,firOrder) && ...
        isequal(cache.passbandRatio,passbandRatio) && ...
        isequal(cache.referenceSolver,referenceSolver) && ...
        isequal(cache.randomSeed,randomSeed);
    if ~isValid
        error("fpf:InvalidReferenceCache",...
            "The cached reference does not match the requested input configuration.");
    end
end
